import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
const logs = [];
page.on('console', m => logs.push({ type: m.type(), text: m.text() }));
page.on('pageerror', e => logs.push({ type: 'pageerror', text: e.message }));
await page.goto('http://localhost:3000/services/sot', { waitUntil: 'networkidle' });
console.log('has_quickstart', await page.getByText('Наборы для быстрого старта').count());
console.log('details_buttons', await page.getByRole('button', { name: 'Подробнее' }).count());
await page.getByRole('button', { name: 'Подробнее' }).first().click();
await page.waitForTimeout(900);
console.log('dialog_count_open', await page.locator('[role="dialog"]').count());
const dialog = page.locator('[role="dialog"]').first();
console.log('dialog_title_has', await dialog.getByText('Антикража + контроль кассы').count());
await dialog.click({ position: { x: 220, y: 220 } });
await page.waitForTimeout(900);
console.log('dialog_count_after_repeat_click', await page.locator('[role="dialog"]').count());
console.log('console_errors', JSON.stringify(logs.filter(l => l.type === 'error' || l.type === 'pageerror').slice(0, 20)));
await browser.close();
